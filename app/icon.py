def _app_icon_png() -> bytes:
    import base64
    return base64.b85decode("".join(_APP_ICON_B85.split()))


@lru_cache(maxsize=1)
def app_icon() -> QIcon:
    """Иконка приложения — встроенный PNG. Для exe-ярлыка он же сохраняется как .ico."""
    pixmap = QPixmap()
    pixmap.loadFromData(_app_icon_png())
    if pixmap.isNull():
        # На всякий случай — пустая иконка, если встроенные данные неожиданно сломались
        pixmap = QPixmap(128, 128)
        pixmap.fill(Qt.transparent)
    if not os.path.exists(ICON_FILE):
        try:
            pixmap.save(ICON_FILE, "ICO")
        except Exception as e:  # noqa: BLE001 — иконка не критична
            log.warning("Не удалось сохранить иконку: %s", e)
    return QIcon(pixmap)
